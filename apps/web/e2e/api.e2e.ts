import { expect, test } from '@playwright/test'

test.afterAll(async ({ request }) => { await request.post('http://127.0.0.1:3010/__test/cleanup') })

test('real API: OAuth, project, invitation, signed event, authorship and logout', async ({ page, browser, request }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Войти через GitHub' }).click()
  await page.getByRole('link', { name: 'Войти как руководитель' }).click()
  await expect(page.getByRole('heading', { name: 'Мои проекты' })).toBeVisible()
  await page.getByLabel('Название организации', { exact: true }).fill('Кафедра API E2E')
  await page.getByRole('button', { name: 'Создать организацию', exact: true }).click()
  await page.getByLabel('Название проекта', { exact: true }).fill('Проект API E2E')
  await page.getByLabel('Начало', { exact: true }).fill('2026-11-01')
  await page.getByLabel('Защита', { exact: true }).fill('2026-12-01')
  await page.getByLabel('Первая команда', { exact: true }).fill('Команда API')
  await page.getByRole('button', { name: 'Создать проект', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Проект API E2E', exact: true })).toBeVisible()
  const projectUrl = page.url()
  await page.getByLabel('Название команды', { exact: true }).fill('Чужая команда')
  await page.getByRole('button', { name: 'Добавить команду', exact: true }).click()
  const otherHref = await page.getByRole('link', { name: 'Чужая команда', exact: true }).getAttribute('href')
  const ownHref = await page.getByRole('link', { name: 'Команда API', exact: true }).getAttribute('href')
  const teamId = ownHref!.split('/').at(-1)!
  await page.getByRole('button', { name: 'Создать приглашение', exact: true }).click()
  const invitation = await page.getByLabel('Ссылка приглашения (действует 7 дней)').inputValue()
  await page.goto(ownHref!)
  await page.getByLabel('Репозиторий (владелец/название)').fill('test/repo')
  await page.getByRole('button', { name: 'Подключить репозиторий', exact: true }).click()
  await expect(page.getByText('Проверяем состояние…')).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Загрузка истории', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Отключить репозиторий', exact: true }).click()
    await page.getByRole('button', { name: 'Подтвердить отключение', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Восстановить подключение GitHub', exact: true })).toBeVisible()
    await expect(page.getByText('Сбор событий остановлен пользователем. Сохранённая история доступна ниже.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Подключить повторно', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Восстановить подключение GitHub', exact: true })).toHaveCount(0)

  const context = await browser.newContext()
  const student = await context.newPage()
  try {
    await student.goto(invitation)
    await student.getByRole('button', { name: 'Войти через GitHub' }).click()
    await student.getByRole('link', { name: 'Войти как студент' }).click()
    await expect(student.getByRole('heading', { name: 'Приглашение: Проект API E2E' })).toBeVisible()
    await student.getByRole('combobox', { name: 'Команда', exact: true }).selectOption(teamId)
    await student.getByRole('button', { name: 'Вступить в команду', exact: true }).click()
    await expect(student.getByRole('heading', { name: 'Команда API', exact: true })).toBeVisible()
    const emit = await request.post('http://127.0.0.1:3010/__test/emit')
    expect(emit.ok()).toBe(true)
    await student.reload()
    await expect(student.getByRole('link', { name: 'Событие из тестового GitHub', exact: true })).toBeVisible()
    await student.getByRole('button', { name: 'Это мой автор', exact: true }).click()
    await expect(student.getByRole('article').filter({ hasText: 'Событие из тестового GitHub' })).toContainText('Студент API')
    await student.getByRole('link', { name: 'Студент API', exact: true }).click()
    await expect(student.getByText('commit: 1', { exact: true })).toBeVisible()
    await expect(student.getByText('Это число событий GitHub. Взвешенный вклад ещё не рассчитан.')).toBeVisible()
    await student.goto(projectUrl)
    await expect(student.getByRole('link', { name: 'Чужая команда', exact: true })).toHaveCount(0)
    const forbidden = await student.request.get('http://127.0.0.1:4174/api/teams/' + otherHref!.split('/').at(-1))
    expect(forbidden.status()).toBe(404)
    // Manage the same real membership through the owner UI.
    await page.goto(projectUrl)
    const studentLogin = (await (await student.request.get('/api/auth/me')).json()).user.githubLogin as string
    await page.getByLabel('GitHub-логин руководителя', { exact: true }).fill(studentLogin)
    await page.getByRole('button', { name: 'Назначить руководителя', exact: true }).click()
    await expect(page.getByRole('button', { name: `Снять права: ${studentLogin}`, exact: true })).toBeVisible()
    await page.getByRole('button', { name: `Снять права: ${studentLogin}`, exact: true }).click()
    await expect(page.getByRole('button', { name: `Снять права: ${studentLogin}`, exact: true })).toHaveCount(0)
    await page.getByRole('combobox', { name: `Роль ${studentLogin}`, exact: true }).selectOption('observer')
    await expect.poll(async () => (await (await student.request.get('/api/workspace')).json()).projects[0].teams[0].canConnect).toBe(false)
    await page.getByRole('combobox', { name: `Роль ${studentLogin}`, exact: true }).selectOption('participant')
    await expect.poll(async () => (await (await student.request.get('/api/workspace')).json()).projects[0].teams[0].canConnect).toBe(true)
    await page.getByRole('button', { name: 'Пригласить наблюдателя', exact: true }).click()
    const observerLink = await page.getByLabel('Ссылка для наблюдателя', { exact: true }).inputValue()
    const observerToken = observerLink.split('/').at(-1)!
    expect((await (await student.request.get('/api/invitations/' + observerToken)).json()).role).toBe('observer')
    await page.getByRole('button', { name: 'Отозвать приглашение', exact: true }).first().click()
    await expect.poll(async () => (await student.request.get('/api/invitations/' + observerToken)).status()).toBe(404)
    await page.getByRole('button', { name: `Удалить из команды: ${studentLogin}`, exact: true }).click()
    await page.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
    await expect.poll(async () => (await student.request.get('/api/teams/' + teamId)).status()).toBe(404)
    await student.getByRole('button', { name: 'Выйти', exact: true }).click()
    await expect(student.getByRole('button', { name: 'Войти через GitHub' })).toBeVisible()
    expect((await student.request.get('http://127.0.0.1:4174/api/auth/me')).status()).toBe(401)
  } finally { await context.close() }
})
