import { expect, test, type Page } from '@playwright/test'

async function signInAsTeacher(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Войти через GitHub' }).click()
  await expect(page.getByRole('heading', { name: 'Мои проекты' })).toBeVisible()
}

test('creates a project, joins by invitation and confirms a demo commit', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await signInAsTeacher(page)
  await page.getByRole('button', { name: '+ Новый проект', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Новый проект' })
  await dialog.getByLabel('Название проекта').fill('Практика TeamPulse')
  await dialog.getByLabel('Начало').fill('2026-11-16')
  await dialog.getByLabel('Защита').fill('2026-12-20')
  await dialog.getByLabel('Первая команда').fill('Север')
  await dialog.getByRole('button', { name: 'Создать проект' }).click()
  await expect(page.getByRole('heading', { name: 'Практика TeamPulse' })).toBeVisible()

  await page.locator('summary').getByText('Ссылка-приглашение').click()
  const invite = await page.getByRole('textbox', { name: 'Ссылка-приглашение' }).inputValue()
  await page.goto(invite)
  await page.getByRole('button', { name: 'Войти через GitHub' }).click()
  await expect(page.getByRole('radio', { name: /Север/ })).toBeChecked()
  await page.getByRole('button', { name: 'Перейти к команде' }).click()
  await expect(page.getByRole('heading', { name: /Север/ })).toBeVisible()
  await expect(page.getByText('Событий пока нет.')).toBeVisible()

  await page.goto('/invite/web-2026')
  await page.getByRole('radio', { name: /Кодзилла/ }).check()
  await page.getByRole('button', { name: 'Перейти к команде' }).click()
  await expect(page.getByRole('heading', { name: /Кодзилла/ })).toBeVisible()
  await expect(page.getByText(/Приняла pull request #34/)).toBeVisible()
  await expect(page.getByTestId('weekly-chart').locator('svg.recharts-surface').first()).toBeVisible()
  await page.getByRole('button', { name: 'Лента событий' }).click()
  await page.getByRole('button', { name: 'Это мой коммит' }).click()
  await expect(page.getByText('Все коммиты привязаны к авторам.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Все коммиты привязаны к авторам.')).toBeVisible()
  await expect(page.getByText('Неопознанный автор')).toHaveCount(0)

  await page.goto('/projects/web/teams/404')
  await expect(page.getByRole('heading', { name: 'Команда недоступна' })).toBeVisible()
  await page.goto('/projects/web/settings')
  await expect(page.getByRole('heading', { name: 'Настройки недоступны' })).toBeVisible()
  expect(pageErrors).toEqual([])
})

test('views weekly summaries, saves settings and prints the team report', async ({ page }) => {
  await page.addInitScript(() => { window.print = () => { document.documentElement.dataset.printRequested = 'yes' } })
  await signInAsTeacher(page)
  await page.goto('/projects/web')
  const teams = page.getByLabel('Команды проекта').getByRole('link')
  await expect(teams.first()).toContainText('Кодзилла')
  await expect(teams.last()).toContainText('Норма')
  await page.getByRole('link', { name: 'Сводка за неделю', exact: true }).click()
  await page.getByRole('button', { name: '21–27 сен' }).click()
  await expect(page.getByRole('button', { name: '21–27 сен' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Обновить сводку' })).toBeDisabled()
  await page.getByRole('button', { name: '5–11 окт' }).click()
  await page.getByRole('button', { name: 'Обновить сводку' }).click()
  await expect(page.getByText(/На этой неделе требуют внимания/)).toBeVisible()
  const mailing = page.getByRole('switch', { name: 'Отправлять командам их сводку' })
  await mailing.click()
  await expect(mailing).not.toBeChecked()
  await page.reload()
  await expect(mailing).not.toBeChecked()

  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.getByRole('slider', { name: 'Вес: Код' }).press('ArrowRight')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Сумма весов видов работы должна быть 100%.')
  await page.getByRole('slider', { name: 'Вес: Код' }).press('ArrowLeft')
  await page.getByRole('spinbutton', { name: 'Тишина', exact: true }).fill('9')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Настройки сохранены')
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'Тишина', exact: true })).toHaveValue('9')

  await page.goto('/projects/web/teams/kodzilla/members/petr')
  await expect(page.getByRole('heading', { name: /Пётр Смирнов/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Работы участника' })).toBeVisible()
  await page.goto('/projects/web/teams/kodzilla/report')
  await expect(page.getByRole('heading', { name: 'Вклад участников' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'История флагов' })).toBeVisible()
  await page.getByRole('button', { name: 'Сохранить как PDF' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-print-requested', 'yes')
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('button', { name: 'Печать' })).toBeHidden()
  await expect(page.getByRole('heading', { name: 'История флагов' })).toBeVisible()
})

test('keeps the mobile workspace within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signInAsTeacher(page)
  await page.goto('/projects/web/teams/kodzilla')
  await expect(page.getByRole('heading', { name: /Кодзилла/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Вклад по видам работы' })).toBeVisible()
  expect(await page.locator('body').evaluate(body => body.scrollWidth)).toBeLessThanOrEqual(390)
})
